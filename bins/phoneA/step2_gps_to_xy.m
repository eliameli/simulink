%% step2_gps_to_xy.m — GPS (широта/долгота) -> декартовы координаты x,y
%
% Телефон A, Location.csv. Два способа перевода широты/долготы в метры,
% и оценка, насколько велика ошибка от того, что Земля не плоская.


clear; clc; close all;

if ~exist(fullfile('..','figs'), 'dir')
    mkdir(fullfile('..','figs'));
end

%% 1) Чтение GPS
loc_file = fullfile('..', 'data', 'phone_A_sensorlogger', 'Location.csv');
L = readtable(loc_file);

lat_deg = L.latitude;     % широта, градусы
lon_deg = L.longitude;    % долгота, градусы
h       = L.altitude;     % высота, метры

%% 2) Опорная точка (начало координат) - просто среднее по треку
lat0_deg = mean(lat_deg);
lon0_deg = mean(lon_deg);
h0       = mean(h);

lat  = deg2rad(lat_deg);   lat0 = deg2rad(lat0_deg);   % дальше всё в радианах
lon  = deg2rad(lon_deg);   lon0 = deg2rad(lon0_deg);

%% 3) Способ 1 - точный, через ECEF (геоцентрические XYZ) и ENU
% Эллипсоид WGS-84 0 - модель земли
% a - большая полуось
%  - сжатие.
a = 6378137;                  % м
f = 1 / 298.257223563;
e2 = 2*f - f^2;                % квадрат эксцентриситета эллипсоида

% N(phi) - радиус кривизны первого вертикала: 
% расстояние от поверхности эллипсоида до 
% оси вращения Земли вдоль нормали к поверхности в данной
% точке. 
% Нужен, чтобы перейти от (широта,долгота,высота) к XYZ.

N = @(phi) a ./ sqrt(1 - e2 * sin(phi).^2);

% Широта/долгота/высота -> геоцентрические XYZ (ось Z - на северный
% полюс, ось X - на пересечение экватора и нулевого меридиана).
ecef = @(phi, lam, hh) deal( ...
    (N(phi) + hh) .* cos(phi) .* cos(lam), ...             % X
    (N(phi) + hh) .* cos(phi) .* sin(lam), ...              % Y
    (N(phi) .* (1 - e2) + hh) .* sin(phi) );                % Z

[X, Y, Z]    = ecef(lat, lon, h);
[X0, Y0, Z0] = ecef(lat0, lon0, h0);   % то же самое для опорной точки

dX = X - X0; dY = Y - Y0; dZ = Z - Z0;

% Поворот (dX,dY,dZ) из ECEF в ENU (восток-север-верх) относительно
% опорной точки (lat0,lon0). Это стандартная матрица поворота ECEF->ENU,
% выведенная из геометрии: ось "восток" всегда горизонтальна и
% перпендикулярна меридиану опорной точки, "север" и "верх" дальше
% зависят ещё и от широты опорной точки.
east_1  =  -sin(lon0).*dX + cos(lon0).*dY;
north_1 =  -sin(lat0).*cos(lon0).*dX - sin(lat0).*sin(lon0).*dY + cos(lat0).*dZ;

x1 = east_1;    % м, способ 1
y1 = north_1;   % м, способ 1

%% 4) Способ 2 - плоское приближение
% Считаем, что около опорной точки Земля локально плоская: долгота
% переводится в метры с поправкой на cos(широта) (на экваторе 1 градус
% долготы - это ~111 км, у полюсов - почти 0), широта - без поправки
% (1 градус широты - всегда ~111 км).
R = 6371000;   % средний радиус Земли, м

x2 = R * cos(lat0) * (lon - lon0);   % "восток", м, способ 2
y2 = R * (lat - lat0);               % "север", м, способ 2

%% 5) Сравнение способов 1 и 2
diff_xy = hypot(x1 - x2, y1 - y2);   % расстояние между двумя оценками одной и той же точки
fprintf('Способ 1 (точный) vs способ 2 (плоский):\n');
fprintf('  макс. расхождение: %.4f м\n', max(diff_xy));
fprintf('  среднее расхождение: %.4f м\n', mean(diff_xy));
fprintf('  (для сравнения, типичная точность GPS - 5-10 м)\n');

%% 6) Оценка "понижения сферы" h(d) = d^2/(2R) - на какой высоте над
% касательной плоскостью была бы точка Земли на расстоянии d, если бы
% Земля была идеально круглой (чисто геометрическая оценка кривизны,
% не связанная с конкретным треком).
d_list_km = 0:0.1:5;
d_list_m  = d_list_km * 1000;
sag_m = d_list_m.^2 / (2*R);

fprintf('Понижение сферы: %.2f м на 2 км, %.2f м на 4 км\n', ...
    (2000)^2/(2*R), (4000)^2/(2*R));

%% 7) Графики
figure('Name', 'Телефон A - GPS в декартовых координатах');

subplot(1,2,1);
plot(x1, y1, 'b.-', 'DisplayName', 'способ 1 (точный)'); hold on;
plot(x2, y2, 'ro--', 'DisplayName', 'способ 2 (плоский)');
grid on; axis equal;
xlabel('x (восток), м'); ylabel('y (север), м');
legend('Location', 'best');
title('Трек в метрах, оба способа поверх друг друга');

subplot(1,2,2);
plot(d_list_km, sag_m, 'k');
grid on;
xlabel('расстояние, км'); ylabel('понижение сферы, м');
title('Насколько Земля "проседает" под касательной плоскостью');

saveas(gcf, fullfile('..', 'figs', 'step2_phoneA_gps_xy.png'));
