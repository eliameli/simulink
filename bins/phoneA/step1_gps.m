%% step1_gps_phoneA.m — GPS-трек телефона A

% Отдельный файл для GPS. Читает Location.csv
% и строит простой график координат - широта от долготы.
%
% Как запускать: открыть в MATLAB, нажать Run (текущая папка - bins/phoneA/)

clear; clc; close all;

%% 1) Чтение файла
loc_file = fullfile('..', 'data', 'phone_A_sensorlogger', 'Location.csv');
L = readtable(loc_file);

t_s = L.seconds_elapsed;   % время от начала записи, секунды
lat = L.latitude;          % широта, градусы
lon = L.longitude;         % долгота, градусы

%% 2) График трека
% x = долгота, y = широта - так привычнее читать как "карту" (восток
% вправо, север вверх).
figure('Name', 'А - GPS (Location.csv)');
plot(lon, lat, 'o-');
grid on; axis equal;
xlabel('долгота, °'); ylabel('широта, °');
title('Телефон A: GPS-трек');

%% 3) Курс (направление движения) по GPS, по времени
% У телефона A столбец bearing в Location.csv всегда = -1 (GPS-чип курс
% не посчитал), поэтому курс считаем сами - по направлению вектора между
% каждой парой соседних GPS-точек.
%
% Формула (плоское приближение, годится на коротких расстояниях - на
% большом участке Земли так делать нельзя, нужна сферическая геометрия,
% но для пары соседних точек в паре сотен метров друг от друга разница
% пренебрежимо мала):
%   "восток"  ~ изменение долготы * cos(широта)  - долгота "сжимается"
%               по мере удаления от экватора, cos(широта) это учитывает
%   "север"   ~ изменение широты
%   курс = atan2(восток, север) - угол от направления на север (0°),
%          по часовой стрелке к востоку (90°) - это и есть обычный
%          компасный курс/азимут, как и bearing/Direction в данных.
lat_rad = deg2rad(lat);
dlat = diff(lat_rad);
dlon = diff(deg2rad(lon));
lat_avg = (lat_rad(1:end-1) + lat_rad(2:end)) / 2;   % средняя широта между двумя точками

east  = dlon .* cos(lat_avg);
north = dlat;
course_deg = mod(rad2deg(atan2(east, north)), 360);   % курс в градусах, 0..360

% курс относится к ИНТЕРВАЛУ между точками i и i+1 - берём время второй
% точки интервала, чтобы было столько же значений курса, сколько и точек
% на графике (кроме самой первой, для неё курса ещё нет)
t_course = t_s(2:end);

%% 4) График курса во времени
figure('Name', 'А - GPS курс во времени');
plot(t_course, course_deg, 'o-');
grid on;
xlabel('время, с'); ylabel('курс, °(от севера, по часовой)');
title('Телефон A: курс по GPS - резкие скачки = повороты');
