function T = f_calc_turn_matrix_from_angles(u)
%
    T1 = [cos(u(2)), 0, sin(u(2));...
          0, 1, 0;...
          -sin(u(2)), 0, cos(u(2))];
    T2 = [cos(u(1)), -sin(u(1)), 0;...
          sin(u(1)), cos(u(1)), 0;...
          0, 0, 1];
    T3 = [1, 0, 0;...
          0, cos(u(3)), -sin(u(3));...
          0, sin(u(3)), cos(u(3))];
    T = T1*T2*T3;

end