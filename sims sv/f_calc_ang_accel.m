function e = f_calc_ang_accel(u, du_dt, d2u_dt2)
%
    e = [0, sin(u(1)), 1;...
         sin(u(3)), cos(u(1))*cos(u(3)), 0;...
         cos(u(3)), -cos(u(1))*sin(u(3)), 0]*d2u_dt2 + ...
        [0, cos(u(1))*du_dt(1), 0;...
         cos(u(3))*du_dt(3), ...
            -sin(u(1))*cos(u(3))*du_dt(1)-cos(u(1))*sin(u(3))*du_dt(3),...
            0;...
         -sin(u(3))*du_dt(3),...
            sin(u(1))*sin(u(3))*du_dt(1)-cos(u(1))*cos(u(3))*du_dt(3),...
            0]*du_dt;

end